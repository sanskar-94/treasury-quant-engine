# PCA
# --------------------------------------------------------------------------- #
class TestPCA:
    @staticmethod
    def _synthetic_changes(n: int = 900) -> pd.DataFrame:
        """Curve changes built from a known 3-factor structure plus noise."""
        rng = np.random.default_rng(7)
        cols = ["3 Mo", "1 Yr", "2 Yr", "5 Yr", "10 Yr", "30 Yr"]
        years = np.array([0.25, 1, 2, 5, 10, 30])
        level = rng.normal(0, 0.0040, n)
        slope = rng.normal(0, 0.0015, n)
        curv = rng.normal(0, 0.0006, n)
        l_load = np.ones(6)
        s_load = (years - years.mean()) / years.std()
        c_load = -((years - 5.0) ** 2) / 100.0
        data = (np.outer(level, l_load) + np.outer(slope, s_load) + np.outer(curv, c_load)
                + rng.normal(0, 0.0002, (n, 6)))
        return pd.DataFrame(data, columns=cols, index=pd.bdate_range("2015-01-01", periods=n))

    def test_three_factors_explain_almost_everything(self):
        p = fit_curve_pca(self._synthetic_changes(), 3)
        assert p.explained_variance_ratio_.sum() > 0.95

    def test_variance_ratios_are_descending(self):
        p = fit_curve_pca(self._synthetic_changes(), 3)
        r = p.explained_variance_ratio_
        assert r[0] > r[1] > r[2]

    def test_pc1_loads_positively_everywhere(self):
        """Sign convention: a positive level score must mean a sell-off."""
        p = fit_curve_pca(self._synthetic_changes(), 3)
        assert (p.components_[0] > 0).all()

    def test_pc2_is_monotone_in_maturity(self):
        """Slope loadings must increase with maturity.

        Tested with Spearman rather than Pearson: the loading is monotone in
        maturity but not *linear* in tenor rank, because the tenor grid itself
        is geometric (0.25y .. 30y). Pearson against rank measures the wrong
        property and reads ~0.77 for a perfectly monotone loading.
        """
        from scipy import stats

        p = fit_curve_pca(self._synthetic_changes(), 3)
        rho = stats.spearmanr(np.arange(len(p.tenors)), p.components_[1]).statistic
        assert rho > 0.9

    def test_pc3_is_a_hump(self):
        """Curvature must move the belly against the wings."""
        p = fit_curve_pca(self._synthetic_changes(), 3)
        v = p.components_[2]
        n = len(v)
        lo, hi = n // 3, 2 * n // 3
        belly = v[lo:hi].mean()
        wings = np.concatenate([v[:lo], v[hi:]]).mean()
        assert np.sign(belly) != np.sign(wings)

    def test_components_are_orthonormal(self):
        p = fit_curve_pca(self._synthetic_changes(), 3)
        gram = p.components_ @ p.components_.T
        assert np.allclose(gram, np.eye(3), atol=1e-8)

    def test_transform_inverse_transform_roundtrip(self):
        ch = self._synthetic_changes()
        p = fit_curve_pca(ch, 6)  # full rank
        assert p.inverse_transform(p.transform(ch)) == pytest.approx(ch.to_numpy(), abs=1e-8)

    def test_factor_frame_is_named(self):
        ch = self._synthetic_changes()
        f = fit_curve_pca(ch, 3).factor_frame(ch)
        assert list(f.columns) == ["level", "slope", "curvature"]

    def test_rolling_factors_are_causal(self):
        """The decisive leakage test.

        Corrupt the tail of the sample and confirm that scores computed before
        the corruption are byte-identical. If loadings leaked from the future,
        changing the future would change the past.
        """
        ch = self._synthetic_changes()
        cut = 600
        base = rolling_pca_factors(ch, window=252, n_factors=3, refit_every=21)

        tampered = ch.copy()
        tampered.iloc[cut:] *= 25.0          # violently change the future only
        after = rolling_pca_factors(tampered, window=252, n_factors=3, refit_every=21)

        a = base.iloc[:cut].dropna()
        b = after.iloc[:cut].dropna()
        assert len(a) > 100
        assert np.allclose(a.to_numpy(), b.loc[a.index].to_numpy(), atol=1e-12)

    def test_rolling_factors_warm_up_is_nan(self):
        ch = self._synthetic_changes()
        f = rolling_pca_factors(ch, window=252, n_factors=3)
        assert f.iloc[:252].isna().all().all()

    def test_rejects_empty_input(self):
        with pytest.raises(ValueError):
            fit_curve_pca(pd.DataFrame({"a": [np.nan, np.nan]}), 1)
